CREATE TABLE RobotMqttSession (
    robot_id BINARY(16) PRIMARY KEY,
    transport_session_id BINARY(16) NOT NULL,
    producer_session_id BINARY(16) NOT NULL,
    owner_instance_id BINARY(16) NOT NULL,
    connection_id BINARY(16) NOT NULL,
    handshake_accepted BOOLEAN NOT NULL,
    handshake_acked BOOLEAN NOT NULL,
    dispatch_ready BOOLEAN NOT NULL,
    closed BOOLEAN NOT NULL,
    hello_json JSON NOT NULL,
    heartbeat_json JSON NULL,
    hello_received_at DATETIME(6) NOT NULL,
    last_heartbeat_at DATETIME(6) NULL,
    failure_reason VARCHAR(2000) NULL,
    FOREIGN KEY (robot_id) REFERENCES Robot(robot_id)
);
CREATE TABLE RobotCommandOutbox (
    command_id BINARY(16) PRIMARY KEY,
    robot_id BINARY(16) NOT NULL,
    job_id BINARY(16) NOT NULL,
    job_step_id BINARY(16) NOT NULL,
    operation_key VARCHAR(150) NOT NULL,
    payload_json JSON NOT NULL,
    expires_at DATETIME(6) NOT NULL,
    state VARCHAR(32) NOT NULL,
    send_attempts INT NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL,
    last_publish_at DATETIME(6) NULL,
    acknowledged_at DATETIME(6) NULL,
    UNIQUE KEY UQ_RobotCommand_step (job_step_id),
    KEY IX_RobotCommand_work (state,created_at),
    FOREIGN KEY (robot_id) REFERENCES Robot(robot_id),
    FOREIGN KEY (job_id) REFERENCES Job(job_id),
    FOREIGN KEY (job_step_id) REFERENCES JobStep(job_step_id)
);
CREATE TABLE RobotMqttInbox (
    message_id BINARY(16) PRIMARY KEY,
    robot_id BINARY(16) NOT NULL,
    producer_session_id BINARY(16) NOT NULL,
    sequence_no BIGINT NOT NULL,
    transport_session_id BINARY(16) NOT NULL,
    message_type VARCHAR(32) NOT NULL,
    canonical_hash CHAR(64) NOT NULL,
    raw_envelope JSON NOT NULL,
    state VARCHAR(24) NOT NULL,
    accepted BOOLEAN NULL,
    response_json JSON NULL,
    received_at DATETIME(6) NOT NULL,
    processed_at DATETIME(6) NULL,
    ack_published_at DATETIME(6) NULL,
    failure_reason VARCHAR(2000) NULL,
    UNIQUE KEY UQ_RobotMqttInbox_producer (producer_session_id,sequence_no),
    KEY IX_RobotMqttInbox_work (state,received_at),
    FOREIGN KEY (robot_id) REFERENCES Robot(robot_id)
);
