CREATE TABLE `Schedule` (
    `schedule_id` BINARY(16) NOT NULL,
    `workflow_id` BINARY(16) NOT NULL,
    `robot_id` BINARY(16) NULL,
    `created_by_account_id` BINARY(16) NULL,
    `schedule_code` VARCHAR(64) NOT NULL,
    `schedule_name` VARCHAR(160) NOT NULL,
    `schedule_type` VARCHAR(24) NOT NULL,
    `timezone` VARCHAR(64) NOT NULL,
    `starts_at` DATETIME(6) NOT NULL,
    `ends_at` DATETIME(6) NULL,
    `interval_sec` INT NULL,
    `cron_expression` VARCHAR(120) NULL,
    `input_template_json` JSON NOT NULL,
    `priority` INT NOT NULL,
    `misfire_policy` VARCHAR(24) NOT NULL,
    `status` VARCHAR(16) NOT NULL,
    `next_run_at` DATETIME(6) NULL,
    `last_run_at` DATETIME(6) NULL,
    `row_version` BIGINT NOT NULL DEFAULT 0,
    `created_at` DATETIME(6) NOT NULL,
    `updated_at` DATETIME(6) NOT NULL,
    CONSTRAINT `pk_schedule` PRIMARY KEY (`schedule_id`),
    CONSTRAINT `uq_schedule_code` UNIQUE (`schedule_code`),
    CONSTRAINT `fk_schedule_workflow` FOREIGN KEY (`workflow_id`) REFERENCES `Workflow` (`workflow_id`),
    CONSTRAINT `fk_schedule_robot` FOREIGN KEY (`robot_id`) REFERENCES `Robot` (`robot_id`),
    CONSTRAINT `fk_schedule_creator` FOREIGN KEY (`created_by_account_id`) REFERENCES `Account` (`account_id`),
    CONSTRAINT `ck_schedule_type` CHECK (`schedule_type` IN ('ONCE','INTERVAL','CRON')),
    CONSTRAINT `ck_schedule_status` CHECK (`status` IN ('ACTIVE','PAUSED','RETIRED')),
    CONSTRAINT `ck_schedule_misfire` CHECK (`misfire_policy` IN ('SKIP','FIRE_ONCE')),
    CONSTRAINT `ck_schedule_priority` CHECK (`priority` BETWEEN 0 AND 100),
    CONSTRAINT `ck_schedule_window` CHECK (`ends_at` IS NULL OR `ends_at` > `starts_at`),
    CONSTRAINT `ck_schedule_shape` CHECK ((`schedule_type` = 'ONCE' AND `interval_sec` IS NULL AND `cron_expression` IS NULL) OR (`schedule_type` = 'INTERVAL' AND `interval_sec` > 0 AND `cron_expression` IS NULL) OR (`schedule_type` = 'CRON' AND `interval_sec` IS NULL AND `cron_expression` IS NOT NULL)),
    INDEX `ix_schedule_due` (`status`, `next_run_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
