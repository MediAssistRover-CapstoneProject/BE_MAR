CREATE TABLE `ServiceRequest` (
    `service_request_id` BINARY(16) NOT NULL,
    `requested_by_account_id` BINARY(16) NULL,
    `requested_robot_id` BINARY(16) NULL,
    `related_incident_id` BINARY(16) NULL,
    `request_code` VARCHAR(64) NOT NULL,
    `request_type` VARCHAR(32) NOT NULL,
    `source_type` VARCHAR(24) NOT NULL,
    `priority` INT NOT NULL,
    `status` VARCHAR(32) NOT NULL,
    `request_note` TEXT NULL,
    `request_data_json` JSON NOT NULL,
    `idempotency_key` VARCHAR(150) NOT NULL,
    `requested_at` DATETIME(6) NOT NULL,
    `scheduled_at` DATETIME(6) NULL,
    `cancelled_at` DATETIME(6) NULL,
    `completed_at` DATETIME(6) NULL,
    `row_version` BIGINT NOT NULL DEFAULT 0,
    `updated_at` DATETIME(6) NOT NULL,
    CONSTRAINT `pk_service_request` PRIMARY KEY (`service_request_id`),
    CONSTRAINT `uq_service_request_code` UNIQUE (`request_code`),
    CONSTRAINT `uq_service_request_idempotency` UNIQUE (`idempotency_key`),
    CONSTRAINT `fk_service_request_account` FOREIGN KEY (`requested_by_account_id`) REFERENCES `Account` (`account_id`),
    CONSTRAINT `fk_service_request_robot` FOREIGN KEY (`requested_robot_id`) REFERENCES `Robot` (`robot_id`),
    CONSTRAINT `ck_service_request_type` CHECK (`request_type` IN ('INFORMATION','NAVIGATION','ESCORT','DELIVERY','EMERGENCY_SOS')),
    CONSTRAINT `ck_service_request_source` CHECK (`source_type` IN ('STAFF_UI','ROBOT_UI','VOICE','SYSTEM','DETECTOR')),
    CONSTRAINT `ck_service_request_status` CHECK (`status` IN ('DRAFT','SUBMITTED','QUEUED','IN_PROGRESS','COMPLETED','FAILED','CANCELLED','RECOVERY_REQUIRED')),
    CONSTRAINT `ck_service_request_priority` CHECK (`priority` BETWEEN 0 AND 100),
    INDEX `ix_service_request_status_time` (`status`, `requested_at`),
    INDEX `ix_service_request_requester` (`requested_by_account_id`, `requested_at`),
    INDEX `ix_service_request_incident` (`related_incident_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

