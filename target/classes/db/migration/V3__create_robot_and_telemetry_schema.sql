CREATE TABLE `Robot` (
    `robot_id` BINARY(16) NOT NULL,
    `current_map_id` BINARY(16) NULL,
    `robot_code` VARCHAR(64) NOT NULL,
    `robot_name` VARCHAR(160) NOT NULL,
    `model` VARCHAR(100) NOT NULL,
    `serial_number` VARCHAR(100) NULL,
    `runtime_version` VARCHAR(64) NULL,
    `firmware_version` VARCHAR(64) NULL,
    `protocol_version` INT NOT NULL DEFAULT 1,
    `capabilities_json` JSON NOT NULL,
    `deployed_catalog_hash` CHAR(64) NULL,
    `map_asset_hash` CHAR(64) NULL,
    `status` VARCHAR(32) NOT NULL,
    `battery_raw` INT NULL,
    `battery_unit` VARCHAR(32) NULL,
    `battery_percent` DECIMAL(5,2) NULL,
    `battery_captured_at` DATETIME(6) NULL,
    `last_heartbeat_at` DATETIME(6) NULL,
    `commissioned_at` DATETIME(6) NULL,
    `device_secret_hash` VARCHAR(100) NULL,
    `device_token_version` BIGINT NOT NULL DEFAULT 0,
    `device_secret_rotated_at` DATETIME(6) NULL,
    `row_version` BIGINT NOT NULL DEFAULT 0,
    `created_at` DATETIME(6) NOT NULL,
    `updated_at` DATETIME(6) NOT NULL,
    PRIMARY KEY (`robot_id`),
    CONSTRAINT `UQ_Robot_robot_code` UNIQUE (`robot_code`),
    CONSTRAINT `UQ_Robot_serial_number` UNIQUE (`serial_number`),
    CONSTRAINT `FK_Robot_current_map` FOREIGN KEY (`current_map_id`) REFERENCES `Map` (`map_id`),
    CONSTRAINT `CK_Robot_protocol_version` CHECK (`protocol_version` >= 1),
    CONSTRAINT `CK_Robot_status` CHECK (`status` IN ('OFFLINE','STARTING','IDLE','BUSY','EMERGENCY_STOP','ERROR','MAINTENANCE')),
    CONSTRAINT `CK_Robot_battery_raw` CHECK (`battery_raw` IS NULL OR (`battery_raw` >= 0 AND `battery_raw` <= 65535)),
    CONSTRAINT `CK_Robot_battery_percent` CHECK (`battery_percent` IS NULL OR (`battery_percent` >= 0 AND `battery_percent` <= 100)),
    INDEX `IX_Robot_status_heartbeat` (`status`, `last_heartbeat_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `RobotStatusHistory` (
    `robot_status_history_id` BINARY(16) NOT NULL,
    `robot_id` BINARY(16) NOT NULL,
    `job_id` BINARY(16) NULL,
    `previous_status` VARCHAR(32) NULL,
    `new_status` VARCHAR(32) NOT NULL,
    `reason` TEXT NULL,
    `error_code` VARCHAR(100) NULL,
    `recorded_at` DATETIME(6) NOT NULL,
    PRIMARY KEY (`robot_status_history_id`),
    CONSTRAINT `FK_RobotStatusHistory_robot` FOREIGN KEY (`robot_id`) REFERENCES `Robot` (`robot_id`),
    CONSTRAINT `CK_RobotStatusHistory_previous` CHECK (`previous_status` IS NULL OR `previous_status` IN ('OFFLINE','STARTING','IDLE','BUSY','EMERGENCY_STOP','ERROR','MAINTENANCE')),
    CONSTRAINT `CK_RobotStatusHistory_new` CHECK (`new_status` IN ('OFFLINE','STARTING','IDLE','BUSY','EMERGENCY_STOP','ERROR','MAINTENANCE')),
    INDEX `IX_RobotStatusHistory_robot_time` (`robot_id`, `recorded_at`),
    INDEX `IX_RobotStatusHistory_job` (`job_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `RobotLocationHistory` (
    `robot_location_history_id` BINARY(16) NOT NULL,
    `robot_id` BINARY(16) NOT NULL,
    `map_id` BINARY(16) NOT NULL,
    `job_id` BINARY(16) NULL,
    `x_m` DECIMAL(12,4) NOT NULL,
    `y_m` DECIMAL(12,4) NOT NULL,
    `yaw_rad` DECIMAL(10,6) NOT NULL,
    `localization_confidence` DECIMAL(5,4) NULL,
    `is_fresh` BOOLEAN NOT NULL,
    `captured_at` DATETIME(6) NOT NULL,
    `received_at` DATETIME(6) NOT NULL,
    PRIMARY KEY (`robot_location_history_id`),
    CONSTRAINT `FK_RobotLocationHistory_robot` FOREIGN KEY (`robot_id`) REFERENCES `Robot` (`robot_id`),
    CONSTRAINT `FK_RobotLocationHistory_map` FOREIGN KEY (`map_id`) REFERENCES `Map` (`map_id`),
    CONSTRAINT `CK_RobotLocationHistory_yaw` CHECK (`yaw_rad` >= -3.141593 AND `yaw_rad` <= 3.141593),
    CONSTRAINT `CK_RobotLocationHistory_confidence` CHECK (`localization_confidence` IS NULL OR (`localization_confidence` >= 0 AND `localization_confidence` <= 1)),
    INDEX `IX_RobotLocationHistory_robot_time` (`robot_id`, `captured_at`),
    INDEX `IX_RobotLocationHistory_map_time` (`map_id`, `captured_at`),
    INDEX `IX_RobotLocationHistory_job` (`job_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

