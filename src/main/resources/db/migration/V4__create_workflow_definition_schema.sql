CREATE TABLE `Workflow` (
    `workflow_id` BINARY(16) NOT NULL,
    `start_step_id` BINARY(16) NULL,
    `published_by_account_id` BINARY(16) NULL,
    `workflow_code` VARCHAR(80) NOT NULL,
    `version_no` INT NOT NULL,
    `workflow_name` VARCHAR(160) NOT NULL,
    `service_type` VARCHAR(64) NOT NULL,
    `description` TEXT NULL,
    `input_schema_json` JSON NOT NULL,
    `input_ui_json` JSON NOT NULL,
    `default_inputs_json` JSON NOT NULL,
    `output_mapping_json` JSON NOT NULL,
    `required_capabilities_json` JSON NOT NULL,
    `max_duration_sec` INT NOT NULL,
    `max_total_visits` INT NOT NULL,
    `graph_version` INT NOT NULL,
    `schema_version` INT NOT NULL,
    `compiled_definition_json` JSON NULL,
    `definition_hash` CHAR(64) NULL,
    `status` VARCHAR(24) NOT NULL,
    `accepts_new_jobs` BOOLEAN NOT NULL,
    `published_at` DATETIME(6) NULL,
    `row_version` BIGINT NOT NULL DEFAULT 0,
    `created_at` DATETIME(6) NOT NULL,
    `updated_at` DATETIME(6) NOT NULL,
    CONSTRAINT `pk_workflow` PRIMARY KEY (`workflow_id`),
    CONSTRAINT `uq_workflow_code_version` UNIQUE (`workflow_code`, `version_no`),
    CONSTRAINT `fk_workflow_publisher` FOREIGN KEY (`published_by_account_id`) REFERENCES `Account` (`account_id`),
    CONSTRAINT `ck_workflow_status` CHECK (`status` IN ('DRAFT','VALIDATED','PUBLISHED','ARCHIVED')),
    CONSTRAINT `ck_workflow_positive_limits` CHECK (`version_no` > 0 AND `max_duration_sec` > 0 AND `max_total_visits` > 0 AND `graph_version` > 0 AND `schema_version` > 0),
    CONSTRAINT `ck_workflow_accepts_jobs` CHECK (`status` = 'PUBLISHED' OR `accepts_new_jobs` = FALSE)
);

CREATE TABLE `Task` (
    `task_id` BINARY(16) NOT NULL,
    `workflow_id` BINARY(16) NOT NULL,
    `task_code` VARCHAR(80) NOT NULL,
    `task_name` VARCHAR(160) NOT NULL,
    `sequence_no` INT NOT NULL,
    `description` TEXT NULL,
    `config_json` JSON NOT NULL,
    `created_at` DATETIME(6) NOT NULL,
    CONSTRAINT `pk_task` PRIMARY KEY (`task_id`),
    CONSTRAINT `uq_task_workflow_code` UNIQUE (`workflow_id`, `task_code`),
    CONSTRAINT `uq_task_workflow_id` UNIQUE (`workflow_id`, `task_id`),
    CONSTRAINT `uq_task_workflow_sequence` UNIQUE (`workflow_id`, `sequence_no`),
    CONSTRAINT `fk_task_workflow` FOREIGN KEY (`workflow_id`) REFERENCES `Workflow` (`workflow_id`) ON DELETE CASCADE,
    CONSTRAINT `ck_task_sequence` CHECK (`sequence_no` > 0)
);

CREATE TABLE `Step` (
    `step_id` BINARY(16) NOT NULL,
    `workflow_id` BINARY(16) NOT NULL,
    `task_id` BINARY(16) NOT NULL,
    `step_type_code` VARCHAR(40) NOT NULL,
    `step_code` VARCHAR(80) NOT NULL,
    `step_name` VARCHAR(160) NOT NULL,
    `sequence_no` INT NOT NULL,
    `description` TEXT NULL,
    `is_enabled` BOOLEAN NOT NULL,
    `params_json` JSON NOT NULL,
    `input_mapping_json` JSON NOT NULL,
    `timeout_sec` INT NOT NULL,
    `max_attempts` INT NOT NULL,
    `retry_delay_sec` INT NOT NULL,
    `retry_codes_json` JSON NOT NULL,
    `max_visits` INT NOT NULL,
    `audit_level` VARCHAR(16) NOT NULL,
    `created_at` DATETIME(6) NOT NULL,
    CONSTRAINT `pk_step` PRIMARY KEY (`step_id`),
    CONSTRAINT `uq_step_workflow_code` UNIQUE (`workflow_id`, `step_code`),
    CONSTRAINT `uq_step_workflow_id` UNIQUE (`workflow_id`, `step_id`),
    CONSTRAINT `uq_step_workflow_sequence` UNIQUE (`workflow_id`, `sequence_no`),
    CONSTRAINT `fk_step_workflow` FOREIGN KEY (`workflow_id`) REFERENCES `Workflow` (`workflow_id`) ON DELETE CASCADE,
    CONSTRAINT `fk_step_task_same_workflow` FOREIGN KEY (`workflow_id`, `task_id`) REFERENCES `Task` (`workflow_id`, `task_id`) ON DELETE CASCADE,
    CONSTRAINT `ck_step_type_code` CHECK (`step_type_code` IN ('MOVE','INTERACT','DATA_SERVICE','AUTHENTICATE','CONTROL_HARDWARE','HANDLE_PAYLOAD','EXECUTE_SENSING','NOTIFY','WAIT','CHECK_CONDITION','SET_CONTEXT')),
    CONSTRAINT `ck_step_audit_level` CHECK (`audit_level` IN ('BASIC','FULL')),
    CONSTRAINT `ck_step_limits` CHECK (`sequence_no` > 0 AND `timeout_sec` > 0 AND `max_attempts` > 0 AND `retry_delay_sec` >= 0 AND `max_visits` > 0)
);

ALTER TABLE `Workflow`
    ADD CONSTRAINT `fk_workflow_start_step_same_workflow`
        FOREIGN KEY (`workflow_id`, `start_step_id`) REFERENCES `Step` (`workflow_id`, `step_id`);

CREATE TABLE `StepTransition` (
    `transition_id` BINARY(16) NOT NULL,
    `workflow_id` BINARY(16) NOT NULL,
    `from_step_id` BINARY(16) NOT NULL,
    `to_step_id` BINARY(16) NULL,
    `outcome` VARCHAR(16) NOT NULL,
    `condition_json` JSON NULL,
    `priority` INT NOT NULL,
    `is_default` BOOLEAN NOT NULL,
    `terminal_status` VARCHAR(32) NULL,
    CONSTRAINT `pk_step_transition` PRIMARY KEY (`transition_id`),
    CONSTRAINT `uq_transition_route` UNIQUE (`from_step_id`, `outcome`, `priority`),
    CONSTRAINT `fk_transition_workflow` FOREIGN KEY (`workflow_id`) REFERENCES `Workflow` (`workflow_id`) ON DELETE CASCADE,
    CONSTRAINT `fk_transition_from_same_workflow` FOREIGN KEY (`workflow_id`, `from_step_id`) REFERENCES `Step` (`workflow_id`, `step_id`) ON DELETE CASCADE,
    CONSTRAINT `fk_transition_to_same_workflow` FOREIGN KEY (`workflow_id`, `to_step_id`) REFERENCES `Step` (`workflow_id`, `step_id`),
    CONSTRAINT `ck_transition_outcome` CHECK (`outcome` IN ('SUCCESS','FAILURE','TIMEOUT')),
    CONSTRAINT `ck_transition_terminal_status` CHECK (`terminal_status` IS NULL OR `terminal_status` IN ('SUCCEEDED','FAILED','CANCELLED','RECOVERY_REQUIRED')),
    CONSTRAINT `ck_transition_target_xor_terminal` CHECK ((`to_step_id` IS NULL) <> (`terminal_status` IS NULL)),
    CONSTRAINT `ck_transition_priority` CHECK (`priority` >= 1),
    CONSTRAINT `ck_transition_default_condition` CHECK (`is_default` = FALSE OR `condition_json` IS NULL)
);
