CREATE TABLE `KnowledgeDocument` (
  document_id BINARY(16) NOT NULL,
  title VARCHAR(255) NOT NULL,
  category VARCHAR(80) NOT NULL,
  language_code VARCHAR(16) NOT NULL,
  visibility VARCHAR(16) NOT NULL,
  status VARCHAR(24) NOT NULL,
  replaces_document_id BINARY(16) NULL,
  current_version_id BINARY(16) NULL,
  effective_from TIMESTAMP(6) NULL,
  effective_until TIMESTAMP(6) NULL,
  created_by_account_id BINARY(16) NOT NULL,
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  row_version BIGINT NOT NULL DEFAULT 0,
  PRIMARY KEY (document_id),
  CONSTRAINT fk_knowledge_document_replaces FOREIGN KEY (replaces_document_id) REFERENCES `KnowledgeDocument` (document_id),
  CONSTRAINT fk_knowledge_document_creator FOREIGN KEY (created_by_account_id) REFERENCES `Account` (account_id),
  CONSTRAINT chk_knowledge_document_visibility CHECK (visibility IN ('PUBLIC','INTERNAL')),
  CONSTRAINT chk_knowledge_document_status CHECK (status IN ('UPLOADED','PROCESSING','READY','FAILED','ARCHIVED')),
  INDEX ix_knowledge_document_status_visibility (status, visibility, updated_at),
  INDEX ix_knowledge_document_replaces (replaces_document_id)
) ENGINE=InnoDB;

CREATE TABLE `KnowledgeDocumentVersion` (
  version_id BINARY(16) NOT NULL,
  document_id BINARY(16) NOT NULL,
  version_no INT NOT NULL,
  original_filename VARCHAR(255) NOT NULL,
  media_type VARCHAR(100) NOT NULL,
  storage_path VARCHAR(1000) NOT NULL,
  sha256 CHAR(64) NOT NULL,
  size_bytes BIGINT NOT NULL,
  page_count INT NULL,
  extracted_text LONGTEXT NULL,
  extraction_method VARCHAR(32) NULL,
  status VARCHAR(24) NOT NULL,
  error_code VARCHAR(80) NULL,
  error_message VARCHAR(1000) NULL,
  ready_at TIMESTAMP(6) NULL,
  created_at TIMESTAMP(6) NOT NULL,
  PRIMARY KEY (version_id),
  CONSTRAINT fk_knowledge_version_document FOREIGN KEY (document_id) REFERENCES `KnowledgeDocument` (document_id),
  CONSTRAINT uq_knowledge_document_version UNIQUE (document_id, version_no),
  CONSTRAINT chk_knowledge_version_status CHECK (status IN ('UPLOADED','EXTRACTING','OCR','CHUNKING','EMBEDDING','READY','FAILED','ARCHIVED')),
  INDEX ix_knowledge_version_status_created (status, created_at)
) ENGINE=InnoDB;

ALTER TABLE `KnowledgeDocument`
  ADD CONSTRAINT fk_knowledge_document_current_version FOREIGN KEY (current_version_id) REFERENCES `KnowledgeDocumentVersion` (version_id);

CREATE TABLE `KnowledgeChunk` (
  chunk_id BINARY(16) NOT NULL,
  version_id BINARY(16) NOT NULL,
  chunk_index INT NOT NULL,
  heading VARCHAR(500) NULL,
  page_from INT NULL,
  page_to INT NULL,
  content TEXT NOT NULL,
  token_estimate INT NOT NULL,
  qdrant_point_id CHAR(36) NOT NULL,
  created_at TIMESTAMP(6) NOT NULL,
  PRIMARY KEY (chunk_id),
  CONSTRAINT fk_knowledge_chunk_version FOREIGN KEY (version_id) REFERENCES `KnowledgeDocumentVersion` (version_id),
  CONSTRAINT uq_knowledge_chunk_index UNIQUE (version_id, chunk_index),
  CONSTRAINT uq_knowledge_qdrant_point UNIQUE (qdrant_point_id),
  FULLTEXT INDEX ft_knowledge_chunk_content (content),
  INDEX ix_knowledge_chunk_version (version_id)
) ENGINE=InnoDB;

CREATE TABLE `KnowledgeIngestionJob` (
  ingestion_job_id BINARY(16) NOT NULL,
  version_id BINARY(16) NOT NULL,
  status VARCHAR(24) NOT NULL,
  attempt_count INT NOT NULL DEFAULT 0,
  next_attempt_at TIMESTAMP(6) NOT NULL,
  started_at TIMESTAMP(6) NULL,
  ended_at TIMESTAMP(6) NULL,
  error_code VARCHAR(80) NULL,
  error_message VARCHAR(1000) NULL,
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  PRIMARY KEY (ingestion_job_id),
  CONSTRAINT fk_knowledge_ingestion_version FOREIGN KEY (version_id) REFERENCES `KnowledgeDocumentVersion` (version_id),
  CONSTRAINT chk_knowledge_ingestion_status CHECK (status IN ('PENDING','RUNNING','SUCCEEDED','FAILED')),
  INDEX ix_knowledge_ingestion_poll (status, next_attempt_at)
) ENGINE=InnoDB;

