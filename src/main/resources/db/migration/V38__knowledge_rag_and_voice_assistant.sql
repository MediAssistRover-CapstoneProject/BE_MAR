CREATE TABLE `VoiceAssistantTurn` (
  turn_id BINARY(16) NOT NULL,
  voice_interaction_id BINARY(16) NOT NULL,
  sequence_no INT NOT NULL,
  idempotency_key VARCHAR(150) NOT NULL,
  status VARCHAR(24) NOT NULL,
  transcript TEXT NULL,
  detected_language VARCHAR(16) NULL,
  intent VARCHAR(24) NULL,
  answer_text TEXT NULL,
  speech_text VARCHAR(2000) NULL,
  grounding_mode VARCHAR(24) NULL,
  warnings_json JSON NULL,
  model_name VARCHAR(80) NULL,
  latency_ms BIGINT NULL,
  action_json JSON NULL,
  confirmation_nonce_hash CHAR(64) NULL,
  confirmation_expires_at TIMESTAMP(6) NULL,
  confirmed_at TIMESTAMP(6) NULL,
  service_request_id BINARY(16) NULL,
  job_id BINARY(16) NULL,
  audio_path VARCHAR(1000) NULL,
  audio_sha256 CHAR(64) NULL,
  error_code VARCHAR(80) NULL,
  error_message VARCHAR(1000) NULL,
  created_at TIMESTAMP(6) NOT NULL,
  completed_at TIMESTAMP(6) NULL,
  PRIMARY KEY (turn_id),
  CONSTRAINT fk_assistant_turn_interaction FOREIGN KEY (voice_interaction_id) REFERENCES `VoiceInteraction` (voice_interaction_id),
  CONSTRAINT fk_assistant_turn_service_request FOREIGN KEY (service_request_id) REFERENCES `ServiceRequest` (service_request_id),
  CONSTRAINT fk_assistant_turn_job FOREIGN KEY (job_id) REFERENCES `Job` (job_id),
  CONSTRAINT uq_assistant_turn_sequence UNIQUE (voice_interaction_id, sequence_no),
  CONSTRAINT uq_assistant_turn_idempotency UNIQUE (voice_interaction_id, idempotency_key),
  CONSTRAINT chk_assistant_turn_status CHECK (status IN ('RECEIVED','TRANSCRIBING','RETRIEVING','GENERATING','AWAITING_CONFIRMATION','READY','FAILED','CANCELLED')),
  INDEX ix_assistant_turn_created (created_at),
  INDEX ix_assistant_turn_confirmation (confirmation_nonce_hash, confirmation_expires_at)
) ENGINE=InnoDB;

CREATE TABLE `AssistantCitation` (
  citation_id BINARY(16) NOT NULL,
  turn_id BINARY(16) NOT NULL,
  ordinal_no INT NOT NULL,
  source_type VARCHAR(24) NOT NULL,
  document_id BINARY(16) NULL,
  article_id BINARY(16) NULL,
  chunk_id BINARY(16) NULL,
  title VARCHAR(255) NOT NULL,
  locator VARCHAR(255) NULL,
  effective_at TIMESTAMP(6) NULL,
  score DECIMAL(8,6) NULL,
  created_at TIMESTAMP(6) NOT NULL,
  PRIMARY KEY (citation_id),
  CONSTRAINT fk_assistant_citation_turn FOREIGN KEY (turn_id) REFERENCES `VoiceAssistantTurn` (turn_id) ON DELETE CASCADE,
  CONSTRAINT fk_assistant_citation_document FOREIGN KEY (document_id) REFERENCES `KnowledgeDocument` (document_id),
  CONSTRAINT fk_assistant_citation_article FOREIGN KEY (article_id) REFERENCES `HospitalInformationArticle` (article_id),
  CONSTRAINT fk_assistant_citation_chunk FOREIGN KEY (chunk_id) REFERENCES `KnowledgeChunk` (chunk_id),
  CONSTRAINT uq_assistant_citation_ordinal UNIQUE (turn_id, ordinal_no),
  INDEX ix_assistant_citation_turn (turn_id)
) ENGINE=InnoDB;
