CREATE TABLE `Endpoint` (
    `endpoint_id` BINARY(16) NOT NULL,
    `map_id` BINARY(16) NOT NULL,
    `zone_id` BINARY(16) NULL,
    `room_id` BINARY(16) NULL,
    `endpoint_code` VARCHAR(64) NOT NULL,
    `endpoint_name` VARCHAR(160) NOT NULL,
    `endpoint_type` VARCHAR(32) NOT NULL,
    `x_m` DECIMAL(12,4) NOT NULL,
    `y_m` DECIMAL(12,4) NOT NULL,
    `yaw_rad` DECIMAL(10,6) NOT NULL,
    `is_active` BOOLEAN NOT NULL DEFAULT TRUE,
    `is_accessible` BOOLEAN NOT NULL DEFAULT TRUE,
    `is_public` BOOLEAN NOT NULL DEFAULT FALSE,
    `description` TEXT NULL,
    `created_at` DATETIME(6) NOT NULL,
    `updated_at` DATETIME(6) NOT NULL,
    PRIMARY KEY (`endpoint_id`),
    CONSTRAINT `UQ_Endpoint_map_code` UNIQUE (`map_id`, `endpoint_code`),
    CONSTRAINT `UQ_Endpoint_id_map` UNIQUE (`endpoint_id`, `map_id`),
    CONSTRAINT `FK_Endpoint_map` FOREIGN KEY (`map_id`) REFERENCES `Map` (`map_id`),
    CONSTRAINT `FK_Endpoint_zone` FOREIGN KEY (`zone_id`) REFERENCES `Zone` (`zone_id`),
    CONSTRAINT `FK_Endpoint_room` FOREIGN KEY (`room_id`) REFERENCES `Room` (`room_id`),
    CONSTRAINT `CK_Endpoint_type` CHECK (`endpoint_type` IN ('ROOM_STOP', 'PICKUP', 'DROPOFF', 'WAITING', 'CHECKPOINT', 'MANUAL_CHARGE')),
    CONSTRAINT `CK_Endpoint_yaw` CHECK (`yaw_rad` >= -3.141593 AND `yaw_rad` <= 3.141593),
    INDEX `IX_Endpoint_public` (`map_id`, `is_active`, `is_public`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

