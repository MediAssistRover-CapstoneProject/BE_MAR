CREATE TABLE `HospitalInformation` (
    `hospital_information_id` BINARY(16) NOT NULL,
    `updated_by_account_id` BINARY(16) NOT NULL,
    `info_category` VARCHAR(64) NOT NULL,
    `title` VARCHAR(255) NOT NULL,
    `content` TEXT NOT NULL,
    `language_code` VARCHAR(16) NOT NULL,
    `keywords_json` JSON NOT NULL,
    `status` VARCHAR(20) NOT NULL,
    `is_public` BOOLEAN NOT NULL DEFAULT FALSE,
    `effective_from` DATETIME(6) NULL,
    `effective_until` DATETIME(6) NULL,
    `created_at` DATETIME(6) NOT NULL,
    `updated_at` DATETIME(6) NOT NULL,
    PRIMARY KEY (`hospital_information_id`),
    CONSTRAINT `FK_HospitalInformation_updated_by` FOREIGN KEY (`updated_by_account_id`) REFERENCES `Account` (`account_id`),
    CONSTRAINT `CK_HospitalInformation_status` CHECK (`status` IN ('DRAFT', 'PUBLISHED', 'RETIRED')),
    INDEX `IX_HospitalInformation_public` (`status`, `is_public`, `info_category`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `Floor` (
    `floor_id` BINARY(16) NOT NULL,
    `hospital_information_id` BINARY(16) NOT NULL,
    `floor_code` VARCHAR(64) NOT NULL,
    `floor_name` VARCHAR(160) NOT NULL,
    `level_no` INT NULL,
    `display_order` INT NOT NULL,
    `description` TEXT NULL,
    `is_active` BOOLEAN NOT NULL DEFAULT TRUE,
    `created_at` DATETIME(6) NOT NULL,
    `updated_at` DATETIME(6) NOT NULL,
    PRIMARY KEY (`floor_id`),
    CONSTRAINT `UQ_Floor_hospital_code` UNIQUE (`hospital_information_id`, `floor_code`),
    CONSTRAINT `FK_Floor_hospital_information` FOREIGN KEY (`hospital_information_id`) REFERENCES `HospitalInformation` (`hospital_information_id`),
    CONSTRAINT `CK_Floor_display_order` CHECK (`display_order` >= 0),
    INDEX `IX_Floor_active_order` (`is_active`, `display_order`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `Map` (
    `map_id` BINARY(16) NOT NULL,
    `floor_id` BINARY(16) NOT NULL,
    `map_code` VARCHAR(64) NOT NULL,
    `version_no` INT NOT NULL,
    `map_name` VARCHAR(160) NOT NULL,
    `width_m` DECIMAL(12,4) NOT NULL,
    `height_m` DECIMAL(12,4) NOT NULL,
    `resolution_m_per_pixel` DECIMAL(10,6) NOT NULL,
    `origin_x_m` DECIMAL(12,4) NOT NULL,
    `origin_y_m` DECIMAL(12,4) NOT NULL,
    `origin_yaw_rad` DECIMAL(10,6) NOT NULL,
    `frame_id` VARCHAR(64) NOT NULL,
    `map_file_uri` TEXT NOT NULL,
    `asset_hash` CHAR(64) NOT NULL,
    `status` VARCHAR(20) NOT NULL,
    `commissioned_at` DATETIME(6) NULL,
    `created_at` DATETIME(6) NOT NULL,
    `updated_at` DATETIME(6) NOT NULL,
    PRIMARY KEY (`map_id`),
    CONSTRAINT `UQ_Map_code_version` UNIQUE (`map_code`, `version_no`),
    CONSTRAINT `FK_Map_floor` FOREIGN KEY (`floor_id`) REFERENCES `Floor` (`floor_id`),
    CONSTRAINT `CK_Map_version` CHECK (`version_no` >= 1),
    CONSTRAINT `CK_Map_dimensions` CHECK (`width_m` > 0 AND `height_m` > 0 AND `resolution_m_per_pixel` > 0),
    CONSTRAINT `CK_Map_status` CHECK (`status` IN ('DRAFT', 'ACTIVE', 'INACTIVE', 'ARCHIVED')),
    INDEX `IX_Map_floor_status` (`floor_id`, `status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `Zone` (
    `zone_id` BINARY(16) NOT NULL,
    `map_id` BINARY(16) NOT NULL,
    `zone_code` VARCHAR(64) NOT NULL,
    `zone_name` VARCHAR(160) NOT NULL,
    `zone_type` VARCHAR(24) NOT NULL,
    `polygon_json` JSON NOT NULL,
    `speed_limit_mps` DECIMAL(5,3) NULL,
    `capacity_limit` INT NULL,
    `calibrated_area_m2` DECIMAL(12,4) NULL,
    `camera_source_ref` VARCHAR(255) NULL,
    `camera_roi_json` JSON NULL,
    `is_active` BOOLEAN NOT NULL DEFAULT TRUE,
    `is_public` BOOLEAN NOT NULL DEFAULT FALSE,
    `description` TEXT NULL,
    `created_at` DATETIME(6) NOT NULL,
    `updated_at` DATETIME(6) NOT NULL,
    PRIMARY KEY (`zone_id`),
    CONSTRAINT `UQ_Zone_map_code` UNIQUE (`map_id`, `zone_code`),
    CONSTRAINT `FK_Zone_map` FOREIGN KEY (`map_id`) REFERENCES `Map` (`map_id`),
    CONSTRAINT `CK_Zone_type` CHECK (`zone_type` IN ('WAITING', 'CORRIDOR', 'RESTRICTED', 'SERVICE', 'OTHER')),
    CONSTRAINT `CK_Zone_limits` CHECK ((`speed_limit_mps` IS NULL OR `speed_limit_mps` > 0) AND (`capacity_limit` IS NULL OR `capacity_limit` >= 0) AND (`calibrated_area_m2` IS NULL OR `calibrated_area_m2` > 0)),
    INDEX `IX_Zone_public` (`map_id`, `is_active`, `is_public`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

