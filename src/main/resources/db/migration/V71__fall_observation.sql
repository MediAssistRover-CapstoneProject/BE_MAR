CREATE TABLE `FallObservation` (
    `observation_id` BINARY(16) NOT NULL PRIMARY KEY,
    `robot_id` BINARY(16) NOT NULL,
    `job_id` BINARY(16) NOT NULL,
    `job_step_id` BINARY(16) NOT NULL,
    `operation_key` VARCHAR(150) NOT NULL,
    `monitoring_session_id` BINARY(16) NOT NULL,
    `tracking_revision` BINARY(16) NOT NULL,
    `transport_session_id` BINARY(16) NOT NULL,
    `map_id` BINARY(16) NOT NULL,
    `map_asset_hash` VARCHAR(64) NOT NULL,
    `navigation_profile_hash` VARCHAR(64) NULL,
    `track_id` INT NOT NULL,
    `candidate_reason` VARCHAR(64) NOT NULL,
    `continuous_duration_sec` DOUBLE NOT NULL,
    `capture_id` VARCHAR(100) NOT NULL,
    `detected_at` DATETIME(6) NOT NULL,
    `created_at` DATETIME(6) NOT NULL,
    `expires_at` DATETIME(6) NOT NULL,
    `stop_confirmed_at` DATETIME(6) NULL,
    `observe_after` DATETIME(6) NULL,
    `observe_until` DATETIME(6) NULL,
    `completed_at` DATETIME(6) NULL,
    `incident_id` BINARY(16) NULL,
    `state` VARCHAR(24) NOT NULL,
    `completion_reason` VARCHAR(80) NULL,
    `row_version` BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT `fk_fall_observation_job` FOREIGN KEY (`job_id`) REFERENCES `Job` (`job_id`) ON DELETE CASCADE,
    CONSTRAINT `fk_fall_observation_robot` FOREIGN KEY (`robot_id`) REFERENCES `Robot` (`robot_id`),
    CONSTRAINT `ck_fall_observation_state` CHECK (`state` IN ('SUSPENDING','STOP_CONFIRMED','OBSERVING','CLEAR','INCIDENT','INCONCLUSIVE','EXPIRED')),
    INDEX `ix_fall_observation_robot` (`robot_id`,`created_at`),
    INDEX `ix_fall_observation_job` (`job_id`,`state`,`expires_at`),
    INDEX `ix_fall_observation_person` (`robot_id`,`monitoring_session_id`,`tracking_revision`,`track_id`,`created_at`)
);
