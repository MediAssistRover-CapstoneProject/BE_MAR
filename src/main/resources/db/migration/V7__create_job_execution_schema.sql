CREATE TABLE `Job` (
    `job_id` BINARY(16) NOT NULL,
    `workflow_id` BINARY(16) NOT NULL,
    `service_request_id` BINARY(16) NULL,
    `schedule_id` BINARY(16) NULL,
    `robot_id` BINARY(16) NULL,
    `map_id` BINARY(16) NULL,
    `recovery_of_job_id` BINARY(16) NULL,
    `cancel_requested_by_account_id` BINARY(16) NULL,
    `reconciled_by_account_id` BINARY(16) NULL,
    `assigned_staff_account_id` BINARY(16) NULL,
    `job_code` VARCHAR(64) NOT NULL,
    `status` VARCHAR(32) NOT NULL,
    `priority` INT NOT NULL,
    `input_json` JSON NOT NULL,
    `context_json` JSON NOT NULL,
    `result_json` JSON NULL,
    `workflow_hash` CHAR(64) NOT NULL,
    `protocol_version` INT NOT NULL,
    `schema_version` INT NOT NULL,
    `graph_version` INT NOT NULL,
    `schedule_fire_at` DATETIME(6) NULL,
    `schedule_item_key` VARCHAR(150) NULL,
    `dispatch_command_id` BINARY(16) NULL,
    `dispatch_expires_at` DATETIME(6) NULL,
    `queued_at` DATETIME(6) NOT NULL,
    `scheduled_at` DATETIME(6) NULL,
    `accepted_at` DATETIME(6) NULL,
    `started_at` DATETIME(6) NULL,
    `cancel_command_id` BINARY(16) NULL,
    `cancel_requested_at` DATETIME(6) NULL,
    `ended_at` DATETIME(6) NULL,
    `error_code` VARCHAR(100) NULL,
    `failure_reason` TEXT NULL,
    `reconciled_at` DATETIME(6) NULL,
    `reconciliation_note` TEXT NULL,
    `row_version` BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT `pk_job` PRIMARY KEY (`job_id`),
    CONSTRAINT `uq_job_code` UNIQUE (`job_code`),
    CONSTRAINT `uq_job_dispatch_command` UNIQUE (`dispatch_command_id`),
    CONSTRAINT `uq_job_cancel_command` UNIQUE (`cancel_command_id`),
    CONSTRAINT `uq_job_schedule_occurrence` UNIQUE (`schedule_id`, `schedule_fire_at`, `schedule_item_key`),
    CONSTRAINT `fk_job_workflow` FOREIGN KEY (`workflow_id`) REFERENCES `Workflow` (`workflow_id`),
    CONSTRAINT `fk_job_request` FOREIGN KEY (`service_request_id`) REFERENCES `ServiceRequest` (`service_request_id`),
    CONSTRAINT `fk_job_schedule` FOREIGN KEY (`schedule_id`) REFERENCES `Schedule` (`schedule_id`),
    CONSTRAINT `fk_job_robot` FOREIGN KEY (`robot_id`) REFERENCES `Robot` (`robot_id`),
    CONSTRAINT `fk_job_map` FOREIGN KEY (`map_id`) REFERENCES `Map` (`map_id`),
    CONSTRAINT `fk_job_recovery` FOREIGN KEY (`recovery_of_job_id`) REFERENCES `Job` (`job_id`),
    CONSTRAINT `fk_job_cancel_actor` FOREIGN KEY (`cancel_requested_by_account_id`) REFERENCES `Account` (`account_id`),
    CONSTRAINT `fk_job_reconcile_actor` FOREIGN KEY (`reconciled_by_account_id`) REFERENCES `Account` (`account_id`),
    CONSTRAINT `fk_job_assigned_staff` FOREIGN KEY (`assigned_staff_account_id`) REFERENCES `Account` (`account_id`),
    CONSTRAINT `ck_job_status` CHECK (`status` IN ('QUEUED','ACCEPTED','RUNNING','SUCCEEDED','FAILED','CANCELLED','RECOVERY_REQUIRED')),
    CONSTRAINT `ck_job_priority` CHECK (`priority` BETWEEN 0 AND 100),
    CONSTRAINT `ck_job_versions` CHECK (`protocol_version` > 0 AND `schema_version` > 0 AND `graph_version` > 0),
    INDEX `ix_job_robot_status` (`robot_id`, `status`),
    INDEX `ix_job_request` (`service_request_id`),
    INDEX `ix_job_status_queued` (`status`, `queued_at`),
    INDEX `ix_job_assigned_staff` (`assigned_staff_account_id`, `status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `JobTask` (
    `job_task_id` BINARY(16) NOT NULL,
    `job_id` BINARY(16) NOT NULL,
    `task_id` BINARY(16) NOT NULL,
    `sequence_no` INT NOT NULL,
    `task_name_snapshot` VARCHAR(160) NOT NULL,
    `config_snapshot_json` JSON NOT NULL,
    `status` VARCHAR(24) NOT NULL,
    `started_at` DATETIME(6) NULL,
    `ended_at` DATETIME(6) NULL,
    `error_code` VARCHAR(100) NULL,
    `error_details` TEXT NULL,
    CONSTRAINT `pk_job_task` PRIMARY KEY (`job_task_id`),
    CONSTRAINT `uq_job_task_definition` UNIQUE (`job_id`, `task_id`),
    CONSTRAINT `uq_job_task_sequence` UNIQUE (`job_id`, `sequence_no`),
    CONSTRAINT `fk_job_task_job` FOREIGN KEY (`job_id`) REFERENCES `Job` (`job_id`),
    CONSTRAINT `fk_job_task_task` FOREIGN KEY (`task_id`) REFERENCES `Task` (`task_id`),
    CONSTRAINT `ck_job_task_status` CHECK (`status` IN ('PENDING','RUNNING','SUCCEEDED','FAILED','CANCELLED','NOT_VISITED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `JobStep` (
    `job_step_id` BINARY(16) NOT NULL,
    `job_task_id` BINARY(16) NOT NULL,
    `step_id` BINARY(16) NOT NULL,
    `visit_no` INT NOT NULL,
    `execution_sequence_no` BIGINT NOT NULL,
    `step_code_snapshot` VARCHAR(80) NOT NULL,
    `step_type_snapshot` VARCHAR(40) NOT NULL,
    `resolved_inputs_json` JSON NOT NULL,
    `result_json` JSON NULL,
    `status` VARCHAR(24) NOT NULL,
    `attempt_no` INT NOT NULL,
    `operation_key` VARCHAR(150) NOT NULL,
    `timeout_sec_snapshot` INT NOT NULL,
    `started_at` DATETIME(6) NULL,
    `ended_at` DATETIME(6) NULL,
    `error_code` VARCHAR(100) NULL,
    `error_details_json` JSON NULL,
    `row_version` BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT `pk_job_step` PRIMARY KEY (`job_step_id`),
    CONSTRAINT `uq_job_step_operation` UNIQUE (`operation_key`),
    CONSTRAINT `uq_job_step_visit` UNIQUE (`job_task_id`, `step_id`, `visit_no`),
    CONSTRAINT `uq_job_step_execution` UNIQUE (`job_task_id`, `execution_sequence_no`),
    CONSTRAINT `fk_job_step_task` FOREIGN KEY (`job_task_id`) REFERENCES `JobTask` (`job_task_id`),
    CONSTRAINT `fk_job_step_definition` FOREIGN KEY (`step_id`) REFERENCES `Step` (`step_id`),
    CONSTRAINT `ck_job_step_status` CHECK (`status` IN ('PENDING','RUNNING','RETRYING','SUCCEEDED','FAILED','TIMED_OUT','CANCELLED')),
    CONSTRAINT `ck_job_step_limits` CHECK (`visit_no` > 0 AND `execution_sequence_no` > 0 AND `attempt_no` > 0 AND `timeout_sec_snapshot` > 0),
    INDEX `ix_job_step_status_started` (`status`, `started_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `JobEvent` (
    `job_event_id` BINARY(16) NOT NULL,
    `job_id` BINARY(16) NOT NULL,
    `robot_id` BINARY(16) NULL,
    `job_task_id` BINARY(16) NULL,
    `job_step_id` BINARY(16) NULL,
    `actor_account_id` BINARY(16) NULL,
    `producer_type` VARCHAR(24) NOT NULL,
    `producer_session_id` BINARY(16) NOT NULL,
    `sequence_no` BIGINT NOT NULL,
    `event_type` VARCHAR(100) NOT NULL,
    `correlation_key` VARCHAR(150) NULL,
    `attempt_no` INT NULL,
    `previous_status` VARCHAR(32) NULL,
    `new_status` VARCHAR(32) NULL,
    `status_scope` VARCHAR(24) NULL,
    `event_data_json` JSON NOT NULL,
    `occurred_at` DATETIME(6) NOT NULL,
    `received_at` DATETIME(6) NOT NULL,
    `persisted_at` DATETIME(6) NOT NULL,
    CONSTRAINT `pk_job_event` PRIMARY KEY (`job_event_id`),
    CONSTRAINT `uq_job_event_session_sequence` UNIQUE (`producer_session_id`, `sequence_no`),
    CONSTRAINT `fk_job_event_job` FOREIGN KEY (`job_id`) REFERENCES `Job` (`job_id`),
    CONSTRAINT `fk_job_event_robot` FOREIGN KEY (`robot_id`) REFERENCES `Robot` (`robot_id`),
    CONSTRAINT `fk_job_event_task` FOREIGN KEY (`job_task_id`) REFERENCES `JobTask` (`job_task_id`),
    CONSTRAINT `fk_job_event_step` FOREIGN KEY (`job_step_id`) REFERENCES `JobStep` (`job_step_id`),
    CONSTRAINT `fk_job_event_actor` FOREIGN KEY (`actor_account_id`) REFERENCES `Account` (`account_id`),
    CONSTRAINT `ck_job_event_producer` CHECK (`producer_type` IN ('SERVER','ROBOT','ADMIN','STAFF','SCHEDULER')),
    INDEX `ix_job_event_job_time` (`job_id`, `occurred_at`),
    INDEX `ix_job_event_correlation` (`correlation_key`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

