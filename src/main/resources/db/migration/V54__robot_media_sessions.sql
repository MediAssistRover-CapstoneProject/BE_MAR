CREATE TABLE `RobotMediaSession` (
    `session_id` BINARY(16) NOT NULL,
    `robot_id` BINARY(16) NOT NULL,
    `incident_id` BINARY(16) NULL,
    `staff_account_id` BINARY(16) NULL,
    `staff_token_version` BIGINT NULL,
    `active_robot_id` BINARY(16) NULL,
    `mode` VARCHAR(16) NOT NULL,
    `state` VARCHAR(24) NOT NULL,
    `created_at` DATETIME(6) NOT NULL,
    `accepted_at` DATETIME(6) NULL,
    `expires_at` DATETIME(6) NOT NULL,
    `device_seen_at` DATETIME(6) NULL,
    `reconnect_started_at` DATETIME(6) NULL,
    `ended_at` DATETIME(6) NULL,
    `end_reason` VARCHAR(96) NULL,
    `cleanup_pending` BIT(1) NOT NULL DEFAULT b'0',
    `row_version` BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (`session_id`),
    UNIQUE KEY `uq_media_active_robot` (`active_robot_id`),
    KEY `idx_media_incident` (`incident_id`),
    KEY `idx_media_cleanup` (`cleanup_pending`, `ended_at`),
    CONSTRAINT `fk_media_robot` FOREIGN KEY (`robot_id`) REFERENCES `Robot` (`robot_id`),
    CONSTRAINT `fk_media_incident` FOREIGN KEY (`incident_id`) REFERENCES `EmergencyIncident` (`incident_id`) ON DELETE SET NULL,
    CONSTRAINT `fk_media_staff` FOREIGN KEY (`staff_account_id`) REFERENCES `Account` (`account_id`)
);
