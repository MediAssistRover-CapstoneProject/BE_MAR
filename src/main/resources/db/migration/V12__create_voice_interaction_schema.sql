CREATE TABLE `VoiceInteraction` (
    `voice_interaction_id` BINARY(16) NOT NULL,
    `account_id` BINARY(16) NULL,
    `robot_id` BINARY(16) NOT NULL,
    `language_code` VARCHAR(16) NOT NULL,
    `status` VARCHAR(16) NOT NULL,
    `started_at` DATETIME(6) NOT NULL,
    `ended_at` DATETIME(6) NULL,
    `detected_intent` VARCHAR(80) NULL,
    `transcript_summary` TEXT NULL,
    `audio_uri` TEXT NULL,
    PRIMARY KEY (`voice_interaction_id`),
    CONSTRAINT `FK_VoiceInteraction_account` FOREIGN KEY (`account_id`) REFERENCES `Account` (`account_id`),
    CONSTRAINT `FK_VoiceInteraction_robot` FOREIGN KEY (`robot_id`) REFERENCES `Robot` (`robot_id`),
    CONSTRAINT `CK_VoiceInteraction_status` CHECK (`status` IN ('ACTIVE','COMPLETED','CANCELLED','FAILED')),
    CONSTRAINT `CK_VoiceInteraction_period` CHECK (`ended_at` IS NULL OR `ended_at` >= `started_at`),
    INDEX `IX_VoiceInteraction_robot_time` (`robot_id`, `started_at`),
    INDEX `IX_VoiceInteraction_account_time` (`account_id`, `started_at`),
    INDEX `IX_VoiceInteraction_status_time` (`status`, `started_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `VoiceCommand` (
    `voice_command_id` BINARY(16) NOT NULL,
    `voice_interaction_id` BINARY(16) NOT NULL,
    `service_request_id` BINARY(16) NULL,
    `sequence_no` INT NOT NULL,
    `raw_text` TEXT NOT NULL,
    `normalized_text` TEXT NULL,
    `intent_code` VARCHAR(80) NULL,
    `confidence_score` DECIMAL(5,4) NULL,
    `command_type` VARCHAR(64) NOT NULL,
    `parameters_json` JSON NOT NULL,
    `status` VARCHAR(16) NOT NULL,
    `received_at` DATETIME(6) NOT NULL,
    `processed_at` DATETIME(6) NULL,
    PRIMARY KEY (`voice_command_id`),
    CONSTRAINT `UQ_VoiceCommand_interaction_sequence` UNIQUE (`voice_interaction_id`, `sequence_no`),
    CONSTRAINT `FK_VoiceCommand_interaction` FOREIGN KEY (`voice_interaction_id`) REFERENCES `VoiceInteraction` (`voice_interaction_id`),
    CONSTRAINT `FK_VoiceCommand_service_request` FOREIGN KEY (`service_request_id`) REFERENCES `ServiceRequest` (`service_request_id`),
    CONSTRAINT `CK_VoiceCommand_sequence` CHECK (`sequence_no` >= 1),
    CONSTRAINT `CK_VoiceCommand_confidence` CHECK (`confidence_score` IS NULL OR (`confidence_score` >= 0 AND `confidence_score` <= 1)),
    CONSTRAINT `CK_VoiceCommand_status` CHECK (`status` IN ('RECEIVED','RESOLVED','REJECTED','EXECUTED','FAILED')),
    CONSTRAINT `CK_VoiceCommand_processed` CHECK ((`status` = 'RECEIVED' AND `processed_at` IS NULL) OR (`status` <> 'RECEIVED' AND `processed_at` IS NOT NULL)),
    CONSTRAINT `CK_VoiceCommand_period` CHECK (`processed_at` IS NULL OR `processed_at` >= `received_at`),
    INDEX `IX_VoiceCommand_interaction_time` (`voice_interaction_id`, `received_at`),
    INDEX `IX_VoiceCommand_request` (`service_request_id`),
    INDEX `IX_VoiceCommand_status_time` (`status`, `received_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
