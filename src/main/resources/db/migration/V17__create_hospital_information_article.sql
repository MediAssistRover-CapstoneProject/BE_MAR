CREATE TABLE `HospitalInformationArticle` (
    `article_id` BINARY(16) NOT NULL,
    `hospital_information_id` BINARY(16) NOT NULL,
    `updated_by_account_id` BINARY(16) NOT NULL,
    `article_code` VARCHAR(80) NOT NULL,
    `category` VARCHAR(64) NOT NULL,
    `canonical_question` VARCHAR(500) NOT NULL,
    `title` VARCHAR(255) NOT NULL,
    `answer` TEXT NOT NULL,
    `language_code` VARCHAR(16) NOT NULL,
    `keywords_json` JSON NOT NULL,
    `status` VARCHAR(20) NOT NULL,
    `is_public` BOOLEAN NOT NULL DEFAULT FALSE,
    `effective_from` DATETIME(6) NULL,
    `effective_until` DATETIME(6) NULL,
    `row_version` BIGINT NOT NULL DEFAULT 0,
    `created_at` DATETIME(6) NOT NULL,
    `updated_at` DATETIME(6) NOT NULL,
    CONSTRAINT `pk_hospital_information_article` PRIMARY KEY (`article_id`),
    CONSTRAINT `uq_hospital_article_code_language` UNIQUE (`hospital_information_id`,`article_code`,`language_code`),
    CONSTRAINT `fk_hospital_article_hospital` FOREIGN KEY (`hospital_information_id`) REFERENCES `HospitalInformation` (`hospital_information_id`),
    CONSTRAINT `fk_hospital_article_updated_by` FOREIGN KEY (`updated_by_account_id`) REFERENCES `Account` (`account_id`),
    CONSTRAINT `ck_hospital_article_status` CHECK (`status` IN ('DRAFT','PUBLISHED','RETIRED')),
    CONSTRAINT `ck_hospital_article_effective_window` CHECK (`effective_until` IS NULL OR `effective_from` IS NULL OR `effective_until` > `effective_from`),
    INDEX `ix_hospital_article_public_effective` (`status`,`is_public`,`language_code`,`effective_from`,`effective_until`),
    INDEX `ix_hospital_article_category` (`hospital_information_id`,`category`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
